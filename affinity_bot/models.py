"""Data models for affinity-bot."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional


@dataclass(frozen=True)
class Note:
    """A single research note — one row of input.

    Attributes
    ----------
    id : str
        Stable identifier (``n0001``, ``n0002``, ...). Assigned at parse time.
    text : str
        The raw note text. Trimmed but otherwise unmodified.
    source : str | None
        Optional provenance string — e.g. participant id, file name, or
        session label. Passed through unchanged.
    """

    id: str
    text: str
    source: Optional[str] = None

    def to_dict(self) -> dict:
        out: dict = {"id": self.id, "text": self.text}
        if self.source is not None:
            out["source"] = self.source
        return out


@dataclass
class Cluster:
    """A theme cluster — a group of related notes plus their label.

    Attributes
    ----------
    cluster_id : int
        0-indexed cluster number. ``-1`` is reserved for outliers / noise.
    label : str
        A short, human-readable theme label.
        - Rule-based: top TF-IDF terms joined with " · ".
        - LLM-enriched: a short noun phrase generated by the LLM layer.
    rationale : str
        One-sentence rationale describing what unifies the cluster.
        - Rule-based: a fixed terse template (``"shared terms: a, b, c"``).
        - LLM-enriched: a single sentence in the researcher's voice.
    note_ids : list[str]
        IDs of the notes assigned to this cluster.
    keyword_signature : list[str]
        Top distinguishing terms — useful for review and debugging.
    label_source : str
        ``"rule"`` or ``"llm"`` — which path produced the current label.
    is_outlier : bool
        True if this is the outlier bucket (cluster_id == -1).
    """

    cluster_id: int
    label: str
    rationale: str
    note_ids: list[str]
    keyword_signature: list[str] = field(default_factory=list)
    label_source: str = "rule"
    is_outlier: bool = False

    @property
    def size(self) -> int:
        return len(self.note_ids)

    def to_dict(self) -> dict:
        return {
            "cluster_id": self.cluster_id,
            "label": self.label,
            "rationale": self.rationale,
            "note_ids": list(self.note_ids),
            "keyword_signature": list(self.keyword_signature),
            "label_source": self.label_source,
            "is_outlier": self.is_outlier,
            "size": self.size,
        }


@dataclass
class AffinityConfig:
    """Configuration for a clustering run.

    Defaults are chosen to behave well on small qualitative corpora
    (typically 30–300 notes from a handful of interviews). Override
    explicitly when the dataset shape is unusual.

    Attributes
    ----------
    n_clusters : int | None
        Number of clusters. If ``None`` (the default), affinity-bot picks
        a value via a silhouette-style heuristic clamped between
        ``min_clusters`` and ``max_clusters``.
    min_clusters : int
        Lower bound when auto-picking ``n_clusters``.
    max_clusters : int
        Upper bound when auto-picking ``n_clusters``.
    outlier_distance_threshold : float
        Cosine distance from cluster centroid above which a note is
        re-tagged as an outlier (cluster_id == -1). Set to ``1.0`` to
        disable outlier flagging entirely.
    keywords_per_cluster : int
        How many top TF-IDF terms to include in the keyword signature
        and the rule-based label.
    use_llm : bool
        If True (the default), attempt LLM enrichment of cluster labels
        and rationale. If no API key is present or DSPy/LiteLLM is not
        installed, the rule-based output is returned unchanged with a
        warning. ``--no-llm`` on the CLI sets this to False.
    llm_backend : str | None
        ``"anthropic"`` / ``"gemini"`` / ``"openai"``. If ``None``, picks
        the first backend whose API key is set (priority:
        anthropic → gemini → openai).
    llm_model : str | None
        Override the default model string for the chosen backend.
    random_state : int
        Deterministic seed for KMeans initialisation.
    """

    n_clusters: Optional[int] = None
    min_clusters: int = 3
    max_clusters: int = 8
    outlier_distance_threshold: float = 0.85
    keywords_per_cluster: int = 4
    use_llm: bool = True
    llm_backend: Optional[str] = None
    llm_model: Optional[str] = None
    random_state: int = 7

    def __post_init__(self) -> None:
        if self.min_clusters < 2:
            raise ValueError("min_clusters must be >= 2")
        if self.max_clusters < self.min_clusters:
            raise ValueError("max_clusters must be >= min_clusters")
        if self.n_clusters is not None and self.n_clusters < 2:
            raise ValueError("n_clusters must be >= 2 when set explicitly")
        if not (0.0 < self.outlier_distance_threshold <= 1.0):
            raise ValueError("outlier_distance_threshold must be in (0, 1]")
        if self.keywords_per_cluster < 1:
            raise ValueError("keywords_per_cluster must be >= 1")
        if self.llm_backend is not None and self.llm_backend not in {
            "anthropic",
            "gemini",
            "openai",
        }:
            raise ValueError(
                f"llm_backend must be one of anthropic/gemini/openai, "
                f"got {self.llm_backend!r}"
            )


@dataclass
class AffinityResult:
    """Result of a clustering run."""

    notes: list[Note]
    clusters: list[Cluster]
    config: AffinityConfig
    llm_used: bool = False
    llm_backend: Optional[str] = None
    notes_clustered: int = 0
    outlier_count: int = 0
    warnings: list[str] = field(default_factory=list)

    @property
    def cluster_count(self) -> int:
        """Number of non-outlier clusters."""
        return sum(1 for c in self.clusters if not c.is_outlier)

    def cluster_for_note(self, note_id: str) -> Optional[Cluster]:
        for c in self.clusters:
            if note_id in c.note_ids:
                return c
        return None

    def to_dict(self) -> dict:
        return {
            "notes": [n.to_dict() for n in self.notes],
            "clusters": [c.to_dict() for c in self.clusters],
            "llm_used": self.llm_used,
            "llm_backend": self.llm_backend,
            "notes_clustered": self.notes_clustered,
            "outlier_count": self.outlier_count,
            "cluster_count": self.cluster_count,
            "warnings": list(self.warnings),
            "config": {
                "n_clusters": self.config.n_clusters,
                "min_clusters": self.config.min_clusters,
                "max_clusters": self.config.max_clusters,
                "outlier_distance_threshold": self.config.outlier_distance_threshold,
                "keywords_per_cluster": self.config.keywords_per_cluster,
                "use_llm": self.config.use_llm,
                "llm_backend": self.config.llm_backend,
                "random_state": self.config.random_state,
            },
        }
